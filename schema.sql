-- ---------- 1. TABEL ----------

create table if not exists public.suppliers (
  id         bigint generated by default as identity primary key,
  name       text not null,
  contact    text not null,
  phone      text not null,
  address    text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.customers (
  id         bigint generated by default as identity primary key,
  name       text not null,
  phone      text not null default '-',
  email      text default '-',
  address    text not null default '-',
  created_at timestamptz not null default now()
);

create table if not exists public.books (
  id          bigint generated by default as identity primary key,
  isbn        text not null unique,
  title       text not null,
  author      text not null,
  supplier_id bigint not null references public.suppliers(id) on delete restrict,
  price       numeric(14,0) not null check (price >= 0),
  stock       integer not null default 0 check (stock >= 0),
  created_at  timestamptz not null default now()
);

create table if not exists public.sales (
  id          bigint generated by default as identity primary key,
  number      text unique,                                   -- TRX-0001 (diisi otomatis)
  sale_date   date not null default current_date,
  customer_id bigint not null references public.customers(id) on delete restrict,
  book_id     bigint not null references public.books(id)     on delete restrict,
  qty         integer not null check (qty > 0),
  unit_price  numeric(14,0),                                 -- diisi otomatis dari books.price
  total       numeric(14,0),                                 -- diisi otomatis = unit_price * qty
  created_at  timestamptz not null default now()
);

create index if not exists idx_books_supplier  on public.books(supplier_id);
create index if not exists idx_sales_customer  on public.sales(customer_id);
create index if not exists idx_sales_book      on public.sales(book_id);
create index if not exists idx_sales_date      on public.sales(sale_date desc);

-- ---------- 2. TRIGGER STOK OTOMATIS ----------

-- Saat transaksi dibuat: cek stok, kurangi stok, isi harga satuan, total, dan nomor.
create or replace function public.fn_sales_before_insert()
returns trigger
language plpgsql
as $$
declare
  v_price numeric;
  v_stock integer;
begin
  select price, stock into v_price, v_stock
  from public.books where id = new.book_id for update;   -- kunci baris agar aman bila bersamaan

  if not found then
    raise exception 'Buku tidak ditemukan.';
  end if;
  if v_stock < new.qty then
    raise exception 'Stok buku tidak mencukupi (tersisa %, diminta %).', v_stock, new.qty;
  end if;

  update public.books set stock = stock - new.qty where id = new.book_id;

  new.unit_price := v_price;
  new.total      := v_price * new.qty;
  new.number     := 'TRX-' || lpad(new.id::text, 4, '0');
  return new;
end $$;

drop trigger if exists trg_sales_before_insert on public.sales;
create trigger trg_sales_before_insert
before insert on public.sales
for each row execute function public.fn_sales_before_insert();

-- Saat transaksi dihapus: stok dikembalikan.
create or replace function public.fn_sales_after_delete()
returns trigger
language plpgsql
as $$
begin
  update public.books set stock = stock + old.qty where id = old.book_id;
  return old;
end $$;

drop trigger if exists trg_sales_after_delete on public.sales;
create trigger trg_sales_after_delete
after delete on public.sales
for each row execute function public.fn_sales_after_delete();

-- Transaksi tidak bisa diedit (sama seperti aplikasi: hanya tambah / hapus).
create or replace function public.fn_sales_block_update()
returns trigger
language plpgsql
as $$
begin
  raise exception 'Transaksi tidak dapat diubah. Hapus lalu buat transaksi baru.';
end $$;

drop trigger if exists trg_sales_block_update on public.sales;
create trigger trg_sales_block_update
before update on public.sales
for each row execute function public.fn_sales_block_update();

-- ---------- 3. VIEW RINGKASAN (dashboard) ----------

create or replace view public.v_dashboard
with (security_invoker = true) as
select
  (select count(*)                    from public.books)                as total_judul,
  (select coalesce(sum(stock), 0)     from public.books)                as total_stok,
  (select count(*)                    from public.sales)                as total_transaksi,
  (select coalesce(sum(total), 0)     from public.sales)                as total_penjualan;

create or replace view public.v_sales_detail
with (security_invoker = true) as
select s.id, s.number, s.sale_date, c.name as customer_name,
       b.title as book_title, s.qty, s.unit_price, s.total
from public.sales s
join public.customers c on c.id = s.customer_id
join public.books b     on b.id = s.book_id;

-- ---------- 4. ROW LEVEL SECURITY ----------
-- PERHATIAN: aplikasi belum memakai login, jadi policy di bawah mengizinkan
-- role "anon" (kunci publishable) membaca & menulis SEMUA data.
-- Cocok untuk demo/latihan. Untuk produksi, ganti ke "to authenticated"
-- dan aktifkan Supabase Auth.

alter table public.suppliers enable row level security;
alter table public.customers enable row level security;
alter table public.books     enable row level security;
alter table public.sales     enable row level security;

do $$
declare t text;
begin
  foreach t in array array['suppliers','customers','books','sales'] loop
    execute format('drop policy if exists "akses_anon_%1$s" on public.%1$s', t);
    execute format(
      'create policy "akses_anon_%1$s" on public.%1$s for all to anon, authenticated using (true) with check (true)', t);
  end loop;
end $$;

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.suppliers, public.customers, public.books, public.sales to anon, authenticated;
grant select on public.v_dashboard, public.v_sales_detail to anon, authenticated;

